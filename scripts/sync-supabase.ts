/**
 * Keeps the Supabase backend in sync with the game's shared TypeScript:
 *  1. Copies src/game, src/simulation, src/scoring into supabase/functions/_shared
 *     so the Edge Function grades with exactly the same code as the browser.
 *  2. Regenerates the challenge catalog migration from the challenge definitions.
 *
 * Run: npm run supabase:sync   (tests fail if this is out of date)
 */
import { cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CHALLENGES, CONTENT_VERSION } from '../src/game/challenges/index.ts'
import { BASE_POINTS } from '../src/scoring/scoring.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const SHARED_DIRS = ['game', 'simulation', 'scoring']
export const SHARED_TARGET = join(root, 'supabase/functions/_shared')
/**
 * The catalog migration for the current CONTENT_VERSION. Applied migrations are
 * never edited: when you bump CONTENT_VERSION, add a new entry here (with a later
 * timestamp) so `supabase db push` applies the updated catalog.
 */
const CATALOG_MIGRATIONS: Record<number, string> = {
  1: '20261105000100_challenge_catalog.sql',
  2: '20261107000000_challenge_catalog_v2.sql',
}
export const CATALOG_MIGRATION = join(root, 'supabase/migrations', CATALOG_MIGRATIONS[CONTENT_VERSION])

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`

export function catalogSql(): string {
  const rows = CHALLENGES.map((c, i) => {
    const concepts = `array[${c.concepts.map(sqlString).join(', ')}]::text[]`
    const points = c.basePoints ?? BASE_POINTS[c.difficulty]
    return `  (${sqlString(c.id)}, ${sqlString(c.difficulty)}, ${sqlString(c.title)}, ${concepts}, ${points}, ${i + 1}, ${CONTENT_VERSION})`
  })
  return `-- GENERATED by scripts/sync-supabase.ts from src/game/challenges. Do not edit by hand.
-- Re-run \`npm run supabase:sync\` after changing challenges, then apply migrations.
insert into public.challenge_catalog (id, difficulty, title, concepts, base_points, sort_order, content_version) values
${rows.join(',\n')}
on conflict (id) do update set
  difficulty = excluded.difficulty,
  title = excluded.title,
  concepts = excluded.concepts,
  base_points = excluded.base_points,
  sort_order = excluded.sort_order,
  content_version = excluded.content_version;
`
}

export function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name)
    return statSync(full).isDirectory() ? listFiles(full) : [full]
  })
}

function main() {
  rmSync(SHARED_TARGET, { recursive: true, force: true })
  mkdirSync(SHARED_TARGET, { recursive: true })
  for (const dir of SHARED_DIRS) {
    cpSync(join(root, 'src', dir), join(SHARED_TARGET, dir), { recursive: true })
  }
  writeFileSync(
    join(SHARED_TARGET, 'README.md'),
    '# Generated\n\nCopied from `src/` by `npm run supabase:sync`. Do not edit here; edit `src/` and re-run the script.\n',
  )
  writeFileSync(CATALOG_MIGRATION, catalogSql())
  console.log(`Synced ${SHARED_DIRS.join(', ')} to supabase/functions/_shared and wrote ${CHALLENGES.length} catalog rows.`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
